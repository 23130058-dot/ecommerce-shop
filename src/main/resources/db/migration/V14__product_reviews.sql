CREATE TABLE IF NOT EXISTS product_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment VARCHAR(2000) NOT NULL CHECK (LENGTH(BTRIM(comment)) > 0),
    is_sample BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_product_review_user_product UNIQUE (product_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_product_reviews_product_created
    ON product_reviews (product_id, created_at DESC, id DESC);

-- Seed visible sample comments using the existing seeded admin account. These are
-- marked as sample data and are not counted as verified renter reviews.
INSERT INTO product_reviews (product_id, user_id, rating, comment, is_sample, created_at)
SELECT p.id, reviewer.id, seed.rating, seed.comment, TRUE,
       CURRENT_TIMESTAMP - make_interval(days => seed.days_ago)
FROM (VALUES
    ('Sony Alpha A7R V', 5, 'Máy cho ảnh rất chi tiết, lấy nét nhanh và thân máy chắc chắn. Nhận thiết bị đúng lịch.', 12),
    ('RED V-RAPTOR XL', 4, 'Chất lượng hình ảnh chuyên nghiệp, phù hợp quay dự án lớn. Thiết bị hơi nặng khi di chuyển.', 9),
    ('Canon RF 15-35mm', 5, 'Ống kính sắc nét, chống rung tốt và tình trạng máy đúng như mô tả.', 6),
    ('DJI Mavic 3 Pro', 4, 'Hình ảnh đẹp, pin hoạt động ổn định. Khâu nhận và trả thiết bị thuận tiện.', 3)
) AS seed(product_name, rating, comment, days_ago)
JOIN products p ON p.name = seed.product_name
JOIN users reviewer ON LOWER(reviewer.email) = '123@gmail.com'
ON CONFLICT (product_id, user_id) DO NOTHING;

UPDATE products p
SET rating = (SELECT ROUND(AVG(pr.rating)::numeric, 1)
              FROM product_reviews pr WHERE pr.product_id = p.id)
WHERE EXISTS (SELECT 1 FROM product_reviews pr WHERE pr.product_id = p.id AND pr.is_sample = TRUE);
