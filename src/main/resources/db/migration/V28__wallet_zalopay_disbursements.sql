CREATE TABLE IF NOT EXISTS wallet_disbursement_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    partner_order_id VARCHAR(64) NOT NULL UNIQUE,
    amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
    destination_type VARCHAR(16) NOT NULL CHECK (destination_type IN ('WALLET', 'BANK')),
    receiver_last4 VARCHAR(4) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('VERIFYING', 'PROCESSING', 'PENDING', 'COMPLETED', 'FAILED')),
    provider_order_id VARCHAR(64),
    provider_status INTEGER,
    message VARCHAR(300) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_wallet_disbursement_user_created
    ON wallet_disbursement_requests(user_id, created_at DESC, id DESC);

ALTER TABLE wallet_transactions
    DROP CONSTRAINT IF EXISTS wallet_transactions_type_check;

ALTER TABLE wallet_transactions
    ADD CONSTRAINT wallet_transactions_type_check
    CHECK (type IN ('TOP_UP','WITHDRAWAL','WITHDRAWAL_REFUND','OWNER_EARNING','RENTAL_PAYMENT',
                    'RENTAL_REFUND','DEPOSIT_HOLD','DEPOSIT_RELEASE','DEPOSIT_DEDUCTION'));
