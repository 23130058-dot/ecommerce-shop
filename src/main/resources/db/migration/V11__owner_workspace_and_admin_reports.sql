ALTER TABLE reviews
    ADD COLUMN IF NOT EXISTS reviewed_user_id BIGINT REFERENCES users(id),
    ADD COLUMN IF NOT EXISTS communication_rating INTEGER,
    ADD COLUMN IF NOT EXISTS punctuality_rating INTEGER,
    ADD COLUMN IF NOT EXISTS care_rating INTEGER,
    ADD COLUMN IF NOT EXISTS equipment_condition VARCHAR(30),
    ADD COLUMN IF NOT EXISTS is_public BOOLEAN NOT NULL DEFAULT TRUE;

CREATE UNIQUE INDEX IF NOT EXISTS uq_owner_review_per_rental
    ON reviews (user_id, rental_id);

CREATE TABLE IF NOT EXISTS owner_product_schedules (
    product_id BIGINT PRIMARY KEY REFERENCES products(id) ON DELETE CASCADE,
    weekend_price NUMERIC(12, 2),
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS owner_product_blocked_dates (
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    blocked_date DATE NOT NULL,
    PRIMARY KEY (product_id, blocked_date)
);

CREATE TABLE IF NOT EXISTS owner_withdrawal_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id),
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS damage_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_item_id BIGINT NOT NULL UNIQUE REFERENCES rental_items(id),
    owner_id BIGINT NOT NULL REFERENCES users(id),
    description TEXT NOT NULL,
    estimated_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    status VARCHAR(24) NOT NULL DEFAULT 'OPEN',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS owner_chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id BIGINT NOT NULL REFERENCES rentals(id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES users(id),
    receiver_id BIGINT NOT NULL REFERENCES users(id),
    body TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_owner_chat_rental_created
    ON owner_chat_messages (rental_id, created_at, id);

CREATE TABLE IF NOT EXISTS user_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    type VARCHAR(30) NOT NULL,
    title VARCHAR(180) NOT NULL,
    message TEXT NOT NULL,
    target_url VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_user_notifications_user_created
    ON user_notifications (user_id, created_at DESC, id DESC);
