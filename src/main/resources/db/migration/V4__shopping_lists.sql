CREATE TABLE IF NOT EXISTS wishlist_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_wishlist_user_product UNIQUE (user_id, product_id)
);

CREATE INDEX IF NOT EXISTS idx_wishlist_user_created
    ON wishlist_items (user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS compare_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_compare_user_product UNIQUE (user_id, product_id),
    CONSTRAINT uq_compare_user_position UNIQUE (user_id, position)
);

CREATE INDEX IF NOT EXISTS idx_compare_user_position
    ON compare_items (user_id, position);

CREATE INDEX IF NOT EXISTS idx_cart_items_cart
    ON cart_items (cart_id);
