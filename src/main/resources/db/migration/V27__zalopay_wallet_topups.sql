CREATE TABLE wallet_topup_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    order_id VARCHAR(64) NOT NULL UNIQUE,
    request_id VARCHAR(64) NOT NULL UNIQUE,
    amount BIGINT NOT NULL CHECK (amount BETWEEN 10000 AND 50000000),
    order_info VARCHAR(120) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),
    pay_url TEXT,
    provider_transaction_id VARCHAR(80),
    result_code INTEGER,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_wallet_topup_requests_user_created
    ON wallet_topup_requests(user_id, created_at DESC, id DESC);

