ALTER TABLE products
    ADD COLUMN IF NOT EXISTS review_reason VARCHAR(2000);

CREATE TABLE IF NOT EXISTS sentiment_training_samples (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text VARCHAR(2000) NOT NULL CHECK (LENGTH(BTRIM(text)) > 0),
    sentiment VARCHAR(12) NOT NULL CHECK (sentiment IN ('POSITIVE', 'NEUTRAL', 'NEGATIVE')),
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_sentiment_training_samples_created
    ON sentiment_training_samples (created_at DESC, id DESC);
