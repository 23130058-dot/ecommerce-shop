CREATE TABLE IF NOT EXISTS wallet_accounts (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    available_balance NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (available_balance >= 0),
    held_balance NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (held_balance >= 0),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO wallet_accounts(user_id)
SELECT id FROM users ON CONFLICT(user_id) DO NOTHING;

CREATE TABLE IF NOT EXISTS wallet_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    type VARCHAR(32) NOT NULL CHECK (type IN ('TOP_UP','WITHDRAWAL','RENTAL_PAYMENT','RENTAL_REFUND','DEPOSIT_HOLD','DEPOSIT_RELEASE','DEPOSIT_DEDUCTION')),
    amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING','COMPLETED','FAILED')),
    available_after NUMERIC(14, 2) NOT NULL CHECK (available_after >= 0),
    held_after NUMERIC(14, 2) NOT NULL CHECK (held_after >= 0),
    description VARCHAR(300) NOT NULL,
    reference_type VARCHAR(24),
    reference_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_wallet_transactions_user_created
    ON wallet_transactions(user_id, created_at DESC, id DESC);
CREATE UNIQUE INDEX IF NOT EXISTS uq_wallet_transaction_reference
    ON wallet_transactions(user_id, type, reference_type, reference_id)
    WHERE reference_type IS NOT NULL AND reference_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS user_notification_preferences (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    in_app_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    email_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    order_updates BOOLEAN NOT NULL DEFAULT TRUE,
    payment_updates BOOLEAN NOT NULL DEFAULT TRUE,
    disputes BOOLEAN NOT NULL DEFAULT TRUE,
    product_recommendations BOOLEAN NOT NULL DEFAULT FALSE,
    promotions BOOLEAN NOT NULL DEFAULT FALSE,
    quiet_hours_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    quiet_start TIME NOT NULL DEFAULT '22:00',
    quiet_end TIME NOT NULL DEFAULT '07:00',
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO user_notification_preferences(user_id)
SELECT id FROM users ON CONFLICT(user_id) DO NOTHING;

CREATE OR REPLACE FUNCTION lensrent_filter_user_notification()
RETURNS trigger AS $$
DECLARE prefs user_notification_preferences%ROWTYPE;
BEGIN
    SELECT * INTO prefs FROM user_notification_preferences WHERE user_id = NEW.user_id;
    IF NOT FOUND THEN RETURN NEW; END IF;
    IF NOT prefs.in_app_enabled THEN RETURN NULL; END IF;
    IF UPPER(NEW.type) IN ('BOOKING','ORDER','RETURN','DAMAGE') AND NOT prefs.order_updates THEN RETURN NULL; END IF;
    IF UPPER(NEW.type) IN ('PAYMENT','WALLET','DEPOSIT') AND NOT prefs.payment_updates THEN RETURN NULL; END IF;
    IF UPPER(NEW.type) IN ('DISPUTE','REPORT') AND NOT prefs.disputes THEN RETURN NULL; END IF;
    IF UPPER(NEW.type) IN ('PRODUCT_IDEA','RECOMMENDATION') AND NOT prefs.product_recommendations THEN RETURN NULL; END IF;
    IF UPPER(NEW.type) IN ('PROMOTION','COUPON') AND NOT prefs.promotions THEN RETURN NULL; END IF;
    IF prefs.quiet_hours_enabled AND UPPER(NEW.type) IN ('PRODUCT_IDEA','RECOMMENDATION','PROMOTION','COUPON') THEN
        IF (prefs.quiet_start < prefs.quiet_end AND LOCALTIME >= prefs.quiet_start AND LOCALTIME < prefs.quiet_end)
           OR (prefs.quiet_start >= prefs.quiet_end AND (LOCALTIME >= prefs.quiet_start OR LOCALTIME < prefs.quiet_end)) THEN
            RETURN NULL;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_lensrent_notification_preferences ON user_notifications;
CREATE TRIGGER trg_lensrent_notification_preferences
BEFORE INSERT ON user_notifications
FOR EACH ROW EXECUTE FUNCTION lensrent_filter_user_notification();
