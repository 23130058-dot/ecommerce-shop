CREATE TABLE IF NOT EXISTS owner_stores (
    owner_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    store_name VARCHAR(160) NOT NULL,
    description VARCHAR(2000) NOT NULL DEFAULT '',
    city VARCHAR(120),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO owner_stores (owner_id, store_name, description, city)
SELECT u.id,
       COALESCE(NULLIF(BTRIM(u.full_name), ''), 'LensRent') || ' Studio',
       'Gian hàng thiết bị quay chụp trên LensRent. Xem danh sách thiết bị đang nhận lịch thuê.',
       u.city
FROM users u
WHERE EXISTS (SELECT 1 FROM products p WHERE p.owner_id = u.id)
ON CONFLICT (owner_id) DO NOTHING;

CREATE TABLE IF NOT EXISTS marketplace_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    target_type VARCHAR(20) NOT NULL CHECK (target_type IN ('STORE', 'CUSTOMER', 'PRODUCT')),
    target_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
    category VARCHAR(80) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'UNDER_REVIEW', 'RESOLVED', 'REJECTED')),
    resolution_note VARCHAR(2000),
    resolved_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP,
    CHECK ((target_type = 'PRODUCT' AND product_id IS NOT NULL) OR (target_type <> 'PRODUCT' AND target_user_id IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_marketplace_reports_status_created ON marketplace_reports(status, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_marketplace_reports_target_user ON marketplace_reports(target_user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS rental_disputes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_item_id BIGINT NOT NULL REFERENCES rental_items(id) ON DELETE CASCADE,
    damage_report_id BIGINT REFERENCES damage_reports(id) ON DELETE SET NULL,
    reporter_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reason VARCHAR(2000) NOT NULL,
    requested_amount NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (requested_amount >= 0),
    status VARCHAR(24) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'UNDER_REVIEW', 'APPROVED', 'REJECTED')),
    resolution_note VARCHAR(2000),
    resolved_amount NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (resolved_amount >= 0),
    resolved_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_rental_disputes_status_created ON rental_disputes(status, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_rental_disputes_item ON rental_disputes(rental_item_id, created_at DESC);

CREATE TABLE IF NOT EXISTS deposit_settlements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_item_id BIGINT NOT NULL UNIQUE REFERENCES rental_items(id) ON DELETE CASCADE,
    renter_id BIGINT NOT NULL REFERENCES users(id),
    owner_id BIGINT NOT NULL REFERENCES users(id),
    deposit_amount NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (deposit_amount >= 0),
    refunded_amount NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (refunded_amount >= 0),
    deducted_amount NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (deducted_amount >= 0),
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING_REVIEW' CHECK (status IN ('PENDING_REVIEW', 'REFUNDED', 'PARTIAL_REFUND', 'WITHHELD')),
    note VARCHAR(2000),
    resolved_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_deposit_settlements_renter ON deposit_settlements(renter_id, created_at DESC);
