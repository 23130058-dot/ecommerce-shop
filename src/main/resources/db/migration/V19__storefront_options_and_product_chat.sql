ALTER TABLE owner_stores
    ADD COLUMN IF NOT EXISTS address VARCHAR(300),
    ADD COLUMN IF NOT EXISTS contact_phone VARCHAR(40),
    ADD COLUMN IF NOT EXISTS contact_email VARCHAR(180),
    ADD COLUMN IF NOT EXISTS business_hours VARCHAR(300),
    ADD COLUMN IF NOT EXISTS facebook_url VARCHAR(500),
    ADD COLUMN IF NOT EXISTS instagram_url VARCHAR(500),
    ADD COLUMN IF NOT EXISTS logo_url VARCHAR(500),
    ADD COLUMN IF NOT EXISTS cover_image_url VARCHAR(500);

CREATE TABLE IF NOT EXISTS owner_product_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    receiver_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    body VARCHAR(2000) NOT NULL,
    read_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (sender_id <> receiver_id)
);

CREATE INDEX IF NOT EXISTS idx_owner_product_messages_thread
    ON owner_product_messages(product_id, sender_id, receiver_id, id);
CREATE INDEX IF NOT EXISTS idx_owner_product_messages_receiver_unread
    ON owner_product_messages(receiver_id, read_at, created_at DESC);
